"""Command-line entry point for the read-only shard audit."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import yaml

from .audit import DatasetAudit, audit_dataset


SUMMARY_FIELDS = (
    ("shard_count", "Shards"),
    ("total_description_rows", "Description rows"),
    ("total_sft_rows", "SFT rows"),
    ("unique_sample_count", "Unique sample IDs"),
    ("valid_sample_count", "Valid samples"),
    ("fully_paired_count", "Fully paired"),
    ("missing_description_count", "Missing descriptions"),
    ("missing_sft_count", "Missing SFT rows"),
    ("missing_rgb_count", "Missing RGB files"),
    ("missing_meta_count", "Missing metadata files"),
    ("unreadable_rgb_count", "Unreadable RGB files"),
    ("malformed_json_count", "Malformed JSON rows"),
    ("description_disagreement_count", "Description disagreements"),
)


def write_audit_outputs(
    audit: DatasetAudit, json_path: Path, csv_path: Path, markdown_path: Path
) -> None:
    for path in (json_path, csv_path, markdown_path):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(json_path).write_text(
        json.dumps(audit.model_dump(mode="json"), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    with Path(csv_path).open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["metric", "value"])
        for field, _ in SUMMARY_FIELDS:
            writer.writerow([field, getattr(audit, field)])
        for resolution, count in audit.image_resolutions.items():
            writer.writerow([f"rgb_resolution:{resolution}", count])
        for shape, count in audit.hsi_shapes.items():
            writer.writerow([f"hsi_shape:{shape}", count])

    lengths = audit.description_lengths
    lines = [
        "# Dataset Audit",
        "",
        "This report is generated by the read-only shard auditor. Counts below are",
        "derived from `descriptions.jsonl`, `sft.jsonl`, referenced RGB files, and",
        "patch metadata rather than from an assumed schema.",
        "",
        "| Metric | Count |",
        "|---|---:|",
    ]
    lines.extend(
        f"| {label} | {getattr(audit, field):,} |" for field, label in SUMMARY_FIELDS
    )
    lines.extend(
        [
            "",
            "## Artifact distributions",
            "",
            f"- RGB resolutions: `{audit.image_resolutions}`",
            f"- HSI shapes from metadata: `{audit.hsi_shapes}`",
            f"- File formats: `{audit.file_formats}`",
            "",
            "## Description lengths",
            "",
            f"- Minimum: {lengths.minimum}",
            f"- Median: {lengths.median:g}",
            f"- Mean: {lengths.mean:g}",
            f"- 95th percentile: {lengths.p95}",
            f"- Maximum: {lengths.maximum}",
            "",
            "## Integrity findings",
            "",
        ]
    )
    if audit.errors:
        lines.append(f"The audit recorded {len(audit.errors)} structured issue(s).")
        for issue in audit.errors[:50]:
            lines.append(f"- `{issue.code}`: {issue.message}")
        if len(audit.errors) > 50:
            lines.append("- Additional issues are retained in the JSON artifact.")
    else:
        lines.append("No missing, duplicate, malformed, inconsistent, or unreadable required component was found.")
    lines.extend(
        [
            "",
            "## Interpretation boundary",
            "",
            "The RGB files are renderings derived from HSI. The feasibility models do not receive the raw HSI cubes.",
            "",
        ]
    )
    Path(markdown_path).write_text("\n".join(lines), encoding="utf-8")


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--json", type=Path, required=True)
    parser.add_argument("--csv", type=Path, required=True)
    parser.add_argument("--markdown", type=Path, required=True)
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    config = yaml.safe_load(args.config.read_text(encoding="utf-8"))
    root = Path(config["dataset_root"])
    audit = audit_dataset(root)
    write_audit_outputs(audit, args.json, args.csv, args.markdown)
    print(
        f"audited {audit.shard_count} shards; "
        f"{audit.fully_paired_count}/{audit.unique_sample_count} fully paired"
    )


if __name__ == "__main__":
    main()
